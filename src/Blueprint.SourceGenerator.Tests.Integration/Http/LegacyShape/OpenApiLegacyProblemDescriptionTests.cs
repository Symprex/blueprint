using System.Text.Json;
using Blueprint.Runtime.Http;
using Blueprint.SourceGenerator.Tests.Integration.Generators.OperationDescriptors;
using FluentAssertions;

namespace Blueprint.SourceGenerator.Tests.Integration.Http.LegacyShape;

/// <summary>
/// Proves that under Legacy naming the problem-details components and an undocumented enum carry the descriptions
/// legacy Blueprint's document gave them, which the framework cannot read from XML documentation the ASP.NET Core shared
/// framework does not ship, while Default naming describes only what it can read.
/// </summary>
/// <remarks>
/// Every expected text is the one Signature365's 18 legacy documents carry, identical in all of them: 234 property and 36
/// component descriptions (18 documents, each with a <c>ProblemDetails</c> of six described properties and a
/// <c>ValidationProblemDetails</c> of seven, and a description of its own). Legacy gave an enum component without
/// documentation the description <c>""</c> (17 of the 192 enum components: <c>ResourceEventChangeType</c> in ten documents,
/// <c>HttpStatusCode</c>, <c>LogLevel</c> and <c>Visibility</c>), which the generated client reads as the type's comment.
/// </remarks>
public sealed class OpenApiLegacyProblemDescriptionTests
{
    private const string Type = "A URI reference [RFC3986] that identifies the problem type. This specification encourages that, when\ndereferenced, it provide human-readable documentation for the problem type\n(e.g., using HTML [W3C.REC-html5-20141028]).  When this member is not present, its value is assumed to be\n\"about:blank\".";

    private const string Title = "A short, human-readable summary of the problem type. It SHOULD NOT change from occurrence to occurrence\nof the problem, except for purposes of localization (e.g. using proactive content negotiation;\nsee [RFC7231], Section 3.4).";

    private const string Status = "The HTTP status code ([RFC7231], Section 6) generated by the origin server for this occurrence of the problem.";

    private const string Detail = "A human-readable explanation specific to this occurrence of the problem.";

    private const string Instance = "A URI reference that identifies the specific occurrence of the problem. It may or may not yield further information if dereferenced.";

    private const string Extensions = "Extension data that MAY contain additional, problem type specific details. Extension members appear in the same\nnamespace as other members of a problem type.";

    private const string Errors = "Gets the validation errors associated with this instance of ValidationProblemDetails.";

    [Fact]
    public void Under_legacy_naming_the_problem_components_are_described_as_legacy_described_them()
    {
        using var document = Render(OpenApiSchemaNaming.Legacy);

        Description(Schema(document, "ProblemDetails")).Should().Be("A machine-readable format for specifying errors in HTTP API responses based on https://tools.ietf.org/html/rfc7807.");
        Description(Schema(document, "ValidationProblemDetails")).Should().Be("A ProblemDetails for validation errors.");
    }

    [Theory]
    [InlineData("ProblemDetails", "type", Type)]
    [InlineData("ProblemDetails", "title", Title)]
    [InlineData("ProblemDetails", "status", Status)]
    [InlineData("ProblemDetails", "detail", Detail)]
    [InlineData("ProblemDetails", "instance", Instance)]
    [InlineData("ProblemDetails", "extensions", Extensions)]
    [InlineData("ValidationProblemDetails", "type", Type)]
    [InlineData("ValidationProblemDetails", "title", Title)]
    [InlineData("ValidationProblemDetails", "status", Status)]
    [InlineData("ValidationProblemDetails", "detail", Detail)]
    [InlineData("ValidationProblemDetails", "instance", Instance)]
    [InlineData("ValidationProblemDetails", "extensions", Extensions)]
    [InlineData("ValidationProblemDetails", "errors", Errors)]
    public void Under_legacy_naming_a_problem_property_is_described_as_legacy_described_it(string component, string property, string expected)
    {
        using var document = Render(OpenApiSchemaNaming.Legacy);

        Description(Schema(document, component).GetProperty("properties").GetProperty(property)).Should().Be(expected);
    }

    [Fact]
    public void Under_default_naming_the_problem_components_are_not_described()
    {
        using var document = Render(OpenApiSchemaNaming.Default);

        Description(Schema(document, "ProblemDetails")).Should().BeNull();
        Description(Schema(document, "ValidationProblemDetails").GetProperty("properties").GetProperty("errors")).Should().BeNull();
    }

    [Fact]
    public void Under_legacy_naming_an_enum_without_documentation_has_an_empty_description()
    {
        using var document = Render(OpenApiSchemaNaming.Legacy);

        Description(Schema(document, "ResourceEventChangeType")).Should().Be(string.Empty);
    }

    [Fact]
    public void Under_legacy_naming_a_documented_enum_keeps_its_description()
    {
        using var document = Render(OpenApiSchemaNaming.Legacy);

        Description(Schema(document, "LegacyShapeStatus")).Should().Be("The status of a tenant's owner.");
    }

    [Fact]
    public void Under_default_naming_an_enum_without_documentation_has_no_description()
    {
        using var document = Render(OpenApiSchemaNaming.Default);

        Description(Schema(document, "ResourceEventChangeType")).Should().BeNull();
    }

    private static string? Description(JsonElement schema)
    {
        return schema.TryGetProperty("description", out var description) ? description.GetString() : null;
    }

    private static JsonElement Schema(JsonDocument document, string component)
    {
        return document.RootElement.GetProperty("components").GetProperty("schemas").GetProperty(component);
    }

    private static JsonDocument Render(OpenApiSchemaNaming naming)
    {
        var (_, rendered) = OpenApiDocumentEndpoint.Create(
            new IntegrationTestBlueprintApp(),
            new OpenApiInfoOptions { SchemaNaming = naming });

        return JsonDocument.Parse(rendered.Json);
    }
}
