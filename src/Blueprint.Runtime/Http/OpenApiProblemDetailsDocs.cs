using Microsoft.AspNetCore.Mvc;

namespace Blueprint.Runtime.Http;

/// <summary>
/// The descriptions legacy Blueprint's document gave <see cref="ProblemDetails"/>, <see cref="ValidationProblemDetails"/> and
/// their members, which a document rendered as legacy's cannot read from XML documentation, since the ASP.NET Core shared
/// framework ships none.
/// </summary>
/// <remarks>
/// Every text is the one in Signature365's 18 legacy documents (<c>8b40ecc961</c>; <c>Blueprint.Http/ProblemDetails.cs</c>
/// for a member, ASP.NET Core's own summary for the two types and <c>errors</c>), identical in all of them. A description
/// the document can read is preferred to these.
/// </remarks>
internal static class OpenApiProblemDetailsDocs
{
    private static readonly Dictionary<string, string> _memberDescriptions = new(StringComparer.Ordinal)
    {
        ["type"] = "A URI reference [RFC3986] that identifies the problem type. This specification encourages that, when\ndereferenced, it provide human-readable documentation for the problem type\n(e.g., using HTML [W3C.REC-html5-20141028]).  When this member is not present, its value is assumed to be\n\"about:blank\".",
        ["title"] = "A short, human-readable summary of the problem type. It SHOULD NOT change from occurrence to occurrence\nof the problem, except for purposes of localization (e.g. using proactive content negotiation;\nsee [RFC7231], Section 3.4).",
        ["status"] = "The HTTP status code ([RFC7231], Section 6) generated by the origin server for this occurrence of the problem.",
        ["detail"] = "A human-readable explanation specific to this occurrence of the problem.",
        ["instance"] = "A URI reference that identifies the specific occurrence of the problem. It may or may not yield further information if dereferenced.",
        ["extensions"] = "Extension data that MAY contain additional, problem type specific details. Extension members appear in the same\nnamespace as other members of a problem type.",
        ["errors"] = "Gets the validation errors associated with this instance of ValidationProblemDetails.",
    };

    /// <summary>
    /// Returns legacy's description of <paramref name="type"/> when it is <see cref="ProblemDetails"/> or
    /// <see cref="ValidationProblemDetails"/>.
    /// </summary>
    /// <param name="type">The type.</param>
    /// <returns>The description, or <see langword="null"/> for any other type.</returns>
    public static string? GetTypeDescription(Type type)
    {
        if (type == typeof(ProblemDetails))
        {
            return "A machine-readable format for specifying errors in HTTP API responses based on https://tools.ietf.org/html/rfc7807.";
        }

        return type == typeof(ValidationProblemDetails) ? "A ProblemDetails for validation errors." : null;
    }

    /// <summary>
    /// Returns legacy's description of a member of <paramref name="type"/> when it is <see cref="ProblemDetails"/> or
    /// <see cref="ValidationProblemDetails"/>.
    /// </summary>
    /// <param name="type">The type that has the member.</param>
    /// <param name="memberName">The member's name in the document.</param>
    /// <returns>The description, or <see langword="null"/> for any other type or member.</returns>
    public static string? GetMemberDescription(Type type, string memberName)
    {
        return (type == typeof(ProblemDetails) || type == typeof(ValidationProblemDetails)) && _memberDescriptions.TryGetValue(memberName, out var description)
            ? description
            : null;
    }
}
