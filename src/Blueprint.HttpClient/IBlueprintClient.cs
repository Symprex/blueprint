namespace Blueprint.HttpClient;

/// <summary>
/// A typed client the source generator completed, which <c>AddBlueprintClient</c> makes for each resolve with no reflection:
/// the generated <see cref="Create"/> resolves each readonly field the hand-written class declares from the container and
/// passes them to the constructor.
/// </summary>
/// <remarks>
/// Implemented by the generated half of a class marked <see cref="BlueprintClientAttribute"/>; nothing implements it by hand.
/// </remarks>
/// <typeparam name="TSelf">The client class itself.</typeparam>
public interface IBlueprintClient<TSelf>
    where TSelf : IBlueprintClient<TSelf>
{
    /// <summary>
    /// Makes a client over a transport, resolving what its hand-written class declares from the container. A field declared
    /// nullable is left null where the container has none; any other that it cannot supply fails the resolve.
    /// </summary>
    /// <remarks>
    /// A nullable value-type field (<c>int?</c>, <c>TimeSpan?</c>) is resolved as its underlying type, as a container registers
    /// it, and is null where none is registered.
    /// </remarks>
    /// <param name="services">The container the client's dependencies are resolved from.</param>
    /// <param name="client">The transport every call is sent with.</param>
    /// <returns>The new client.</returns>
    static abstract TSelf Create(IServiceProvider services, BlueprintHttpClient client);

    /// <summary>
    /// Makes the transport a call outside the client sends with, as the client's own calls do: a gateway operation's generated
    /// forward (<see cref="BlueprintClientTransport.Create{TClient}"/>) through the client that includes its inner operation.
    /// </summary>
    /// <remarks>
    /// A client declaring a <see cref="BlueprintClientAttribute.SerializerContext"/> applies that context here, as its
    /// constructor does; any other returns the transport unchanged.
    /// </remarks>
    /// <param name="client">The transport made from the client's named <see cref="System.Net.Http.HttpClient"/> and JSON options.</param>
    /// <returns>The transport to send with.</returns>
    static virtual BlueprintHttpClient ConfigureTransport(BlueprintHttpClient client)
    {
        return client;
    }

    /// <summary>
    /// Makes a client that authenticates every request with <paramref name="credential"/>, as the client's own generated
    /// <c>WithCredential</c> does, for code that knows the client only by its type: <c>AddCallerBlueprintClient</c> gives each
    /// resolve the caller's credential through it, with no delegate from the app and no reflection.
    /// </summary>
    /// <remarks>
    /// The credential is applied after every other step that shapes a request, and a clone the client later makes (through
    /// <c>WithRequestModifier</c>) keeps it. Virtual rather than abstract so that a client compiled by an earlier generator
    /// still loads; such a client refuses the call until it is rebuilt.
    /// </remarks>
    /// <param name="client">The client to clone, which is unchanged.</param>
    /// <param name="credential">The credential to authenticate with, replacing any the client has.</param>
    /// <returns>The new client.</returns>
    /// <exception cref="NotSupportedException">The client was generated before this member existed.</exception>
    static virtual TSelf WithCredential(TSelf client, IUpstreamCredential credential)
    {
        throw new NotSupportedException(
            $"{typeof(TSelf).FullName} was generated by an earlier Blueprint.SourceGenerator that did not implement " +
            "IBlueprintClient<TSelf>.WithCredential. Rebuild it with the current generator.");
    }
}
